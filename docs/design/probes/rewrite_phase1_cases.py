def case(name, table, columns, origin, *, params=None, defaults=False, count=False, **options):
    return dict(name=name, table='invc.'+table, columns=columns,
                origin=origin if origin.startswith('gnrpy/') else ORIGIN+'::'+origin,
                params=params or {}, count=count,
                defaults=defaults, options={**({} if defaults else COMMON), **options})


