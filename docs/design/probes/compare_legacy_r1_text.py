"""Compare R1 text helpers with the original functions in one frozen snapshot.

No SQL execution or DB connection. Run each snapshot in its own interpreter.
Only --write-oracle writes the reference fixture used by the portable tests.
"""
import argparse
import json
from pathlib import Path
import sys
from types import SimpleNamespace


def capture(function, *args, **kwargs):
    try:
        return {'value': function(*args, **kwargs)}
    except Exception as error:
        return {'error': type(error).__name__}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--snapshot', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--write-oracle', type=Path)
    args = parser.parse_args()
    sys.path.insert(0, str(args.snapshot / 'gnrpy'))
    sys.path.append('/tmp/asqueel-formula-baseline/env/lib/python3.12/site-packages')
    from gnr.core.gnrstring import split, templateReplace
    from gnr.sql.gnrsql import GnrSqlDb
    from gnr.sql.gnrsqldata.compiler import SqlQueryCompiler
    from asqueel._legacy_sql import FieldReferences, split_sql, template_replace
    from scanner_corpus import CASES

    text_cases = []
    for case in CASES:
        for key, value in [('columns', case['columns']), ('where', case['where']),
                           ('order_by', case['options'].get('order_by'))]:
            if value is not None:
                text_cases.append((case['name'] + ':' + key, value))
    text_cases.extend((f'edge_{i}', value) for i, value in enumerate([
        '', '$id, $id', 'a,(b,c),d', "'a,b', COALESCE($id,0)",
        'a[1,2],b', 'a,(b', 'a,b)', 'a,(b]', '$id+$total,$id',
        '$id AS "display name",CAST($id AS text) AS x',
        '$id;$total', '$id#foo', '@x.y+@x.y,@x.@y.z', '${AND $id=1}',
    ]))
    records = []
    for name, text in text_cases:
        for separator in [',', ' AS ']:
            legacy = capture(split, text, separator)
            current = capture(split_sql, text, separator)
            records.append(dict(kind='split', name=name, text=text, separator=separator,
                                legacy=legacy, current=current))
        for safe in [False, True]:
            for symbols in [{}, {'id': '"t0"."id"', 'total': '"t0"."total"'}]:
                legacy = capture(templateReplace, text, symbols, safeMode=safe)
                current = capture(template_replace, text, symbols, safe=safe)
                records.append(dict(kind='template', name=name, text=text, symbols=symbols,
                                    safe=safe, legacy=legacy, current=current))
    for case in CASES:
        refs = FieldReferences()
        legacy_context = SimpleNamespace(
            cpl=SimpleNamespace(relationDict={}),
            db=SimpleNamespace(colToAs=lambda name: GnrSqlDb.colToAs(None, name)))
        for name, text in [('columns', case['columns']), ('where', case['where']),
                           ('order_by', case['options'].get('order_by'))]:
            if text is None:
                continue
            legacy = capture(SqlQueryCompiler.updateFieldDict, legacy_context, text)
            legacy['paths'] = dict(legacy_context.cpl.relationDict)
            current = capture(refs.discover, text)
            current['paths'] = dict(refs.paths)
            records.append(dict(kind='discover', name=case['name'] + ':' + name,
                                text=text, legacy=legacy, current=current))
    mismatches = [record for record in records if record['legacy'] != record['current']]
    output = dict(snapshot=str(args.snapshot), checks=len(records),
                  mismatches=mismatches, records=records)
    args.output.write_text(json.dumps(output, ensure_ascii=False, indent=2) + '\n')
    if args.write_oracle:
        assert args.snapshot.name == 'legacy'
        assert not mismatches
        oracle = [{k: v for k, v in record.items() if k != 'current'} for record in records]
        args.write_oracle.write_text(json.dumps(dict(
            commit='fa35e5adfa6ad1b269f3a22a9b12c4c1ee6513ea',
            source='Original GenroPy functions; generated by compare_legacy_r1_text.py',
            records=oracle), ensure_ascii=False, indent=2) + '\n')
    print(json.dumps(dict(snapshot=args.snapshot.name, checks=len(records),
                          mismatches=len(mismatches))))
    if mismatches:
        raise SystemExit(1)


if __name__ == '__main__':
    main()
